/**
 * Swedish deliberately starts from the complete English catalogue.  Merging
 * rather than spreading is important here: a partially translated nested
 * section must not make a UI key evaluate to undefined.
 */
function mergeTranslations<T extends Record<string, unknown>>(
  fallback: T,
  translated: Record<string, unknown>,
): T {
  const result: Record<string, unknown> = { ...fallback };
  for (const [key, value] of Object.entries(translated)) {
    const fallbackValue = fallback[key];
    result[key] =
      value && typeof value === "object" && !Array.isArray(value) &&
      fallbackValue && typeof fallbackValue === "object" && !Array.isArray(fallbackValue)
        ? mergeTranslations(fallbackValue as Record<string, unknown>, value as Record<string, unknown>)
        : value;
  }
  return result as T;
}

